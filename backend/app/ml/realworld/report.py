"""Render the real-world evaluation report and model card from a results dict.

Every number comes from the results; none is typed in here.
"""

from typing import Any

NOTICE = (
    "REAL-WORLD DATA, SMALL SAMPLE. Rows come from sandboxed scans of public repositories at "
    "pinned revisions. Labels: known_vulnerable from reviewed GHSA/OSV advisories (established); "
    "benign from metadata criteria (no advisory for that version, verified publisher or signed "
    "release, minimum age), which is not ground truth. 'unknown', suspicious and malicious rows "
    "are excluded. The task is benign vs known_vulnerable: it is not malware detection. "
    "Synthetic data is not used here."
)


def _fmt(value: Any) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.3f}"
    return str(value)


def _metric_table(test: dict[str, Any]) -> list[str]:
    keys = ("precision", "recall", "f1", "roc_auc", "pr_auc", "fpr", "fnr")
    lines = [
        "| Model | " + " | ".join(keys) + " | TP | FP | TN | FN |",
        "|---" * (len(keys) + 5) + "|",
    ]
    for name, m in test.items():
        cells = [_fmt(m.get(k)) for k in keys] + [str(m[k]) for k in ("tp", "fp", "tn", "fn")]
        lines.append(f"| {name} | " + " | ".join(cells) + " |")
    return lines


def render_report(results: dict[str, Any]) -> str:
    out = [
        "# ProvenanceX real-world evaluation report",
        "",
        f"> **{NOTICE}**",
        "",
        "Generated by `ml/scripts/train_realworld.py`. Do not edit by hand.",
        "",
        "## Data",
        "",
        f"- Manifest: `{results['manifest_sha256']}` ({results['dataset_version']})",
        f"- Feature rows read: {results['feature_rows_read']}; usable training rows: "
        f"{results['usable_rows']}",
        f"- Excluded rows by reason: {results['excluded']}",
        f"- Scan outcomes: {results['scan_outcomes']}",
        "",
        "## Sufficiency by artifact type",
        "",
        "| Type | Rows | Class counts | Families | Model trained | Reason |",
        "|---|---|---|---|---|---|",
    ]
    for kind, s in results["sufficiency"].items():
        out.append(
            f"| {kind} | {s['rows']} | {s['class_counts']} | {s['family_counts']} | "
            f"{'yes' if kind in results['models'] else 'no'} | {s['reason'] or ''} |"
        )
    for kind, r in results["models"].items():
        out += [
            "",
            f"## {kind}",
            "",
            f"Split by family (seed {r['seed']}): {r['split_counts']}. Thresholds chosen on "
            "validation only; test scored once.",
            "",
            f"Label evidence check: {r['observability']}",
            "",
            "### Test split",
            "",
            *_metric_table(r["test"]),
            "",
            f"Random Forest test bootstrap 95% CI: {r['test']['random_forest'].get('bootstrap')}",
            "",
            f"Rules-only test bootstrap 95% CI: {r['test']['rules_only'].get('bootstrap')}",
            "",
            "### False positives with no prior scan",
            "",
            "Every real row is a first scan, so comparison features are null (`no_prior_scan`).",
            "",
            "| Model | Benign rows | False positives | FPR |",
            "|---|---|---|---|",
        ]
        for name, m in r["test"].items():
            np_ = m["no_prior_scan"]
            out.append(
                f"| {name} | {np_['benign_rows']} | {np_['false_positives']} | {_fmt(np_['fpr'])} |"
            )
        rf = r["test"]["random_forest"]
        out += [
            "",
            "### Threshold analysis (Random Forest, test)",
            "",
            "| Threshold | Precision | Recall | FPR | FNR |",
            "|---|---|---|---|---|",
            *[
                f"| {t['threshold']} | {_fmt(t['precision'])} | {_fmt(t['recall'])} | "
                f"{_fmt(t['fpr'])} | {_fmt(t['fnr'])} |"
                for t in rf["threshold_analysis"]
            ],
            "",
            "### Calibration (test)",
            "",
            f"- Random Forest: {rf['calibration']}",
            f"- XGBoost: {r['test']['xgboost']['calibration']}",
            "",
            f"### Repeated family splits ({r['repeated']['seeds']} seeds, "
            f"{r['repeated']['skipped']} skipped)",
            "",
            "| Model | Metric | n | mean | std | min | max |",
            "|---|---|---|---|---|---|---|",
        ]
        for name, metrics in r["repeated"]["summary"].items():
            for key, v in metrics.items():
                out.append(
                    f"| {name} | {key} | {v['n']} | {v['mean']} | {v['std']} | {v['min']} | "
                    f"{v['max']} |"
                )
        out += [
            "",
            "### Layer ablation (Random Forest, test)",
            "",
            "| Removed layer | F1 | ROC-AUC | PR-AUC | FPR |",
            "|---|---|---|---|---|",
            *[
                f"| {a['removed_layer']} | {_fmt(a.get('f1'))} | {_fmt(a.get('roc_auc'))} | "
                f"{_fmt(a.get('pr_auc'))} | {_fmt(a.get('fpr'))} |"
                for a in r["ablation"]
            ],
            "",
            f"Top Random Forest features (impurity): {r['top_features']}",
            "",
            "Validation (used for thresholds): RF F1 "
            f"{_fmt(r['validation']['random_forest']['f1'])}, "
            f"rules-only F1 {_fmt(r['validation']['rules_only']['f1'])}",
        ]
    out += ["", "## Evidence gaps", ""] + [f"- {g}" for g in results["evidence_gaps"]]
    return "\n".join(out) + "\n"


def render_model_card(results: dict[str, Any]) -> str:
    out = [
        "# ProvenanceX real-world model card",
        "",
        f"> **{NOTICE}**",
        "",
        "Generated by `ml/scripts/train_realworld.py`.",
        "",
        "- Task: benign vs known_vulnerable, per artifact type, only where real data suffices.",
        "- Models: Random Forest (primary), XGBoost (comparison), Isolation Forest (fit on benign"
        " train rows only).",
        "- Runtime: **not wired in**. The API still uses the synthetic models in `ml/models/`"
        " and keeps ML out of the decision band. These artifacts are research outputs.",
        f"- Artifacts: {', '.join(results['models']) or 'none'} under `ml/models/realworld/`.",
        "",
        "## Results (test split)",
        "",
    ]
    for kind, r in results["models"].items():
        rf, rules = r["test"]["random_forest"], r["test"]["rules_only"]
        out.append(
            f"- {kind}: RF F1 {_fmt(rf['f1'])}, ROC-AUC {_fmt(rf['roc_auc'])},"
            f" FPR {_fmt(rf['fpr'])}"
            f" vs rules-only F1 {_fmt(rules['f1'])}, FPR {_fmt(rules['fpr'])}"
            f" (test n={rf['records']})."
        )
    if not results["models"]:
        out.append("- No artifact type had enough real labelled data; no model was trained.")
    out += ["", "## Not supported", ""] + [f"- {g}" for g in results["evidence_gaps"]]
    return "\n".join(out) + "\n"
