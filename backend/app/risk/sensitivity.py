"""How much do decisions move when one weight changes? Analysis only: nothing is fitted.

Runs on the synthetic validation split and refuses any other split. The result describes the
hand-set parameters. It is not a validation of them, and it must not be used to pick weights.
"""

from collections import Counter
from collections.abc import Sequence
from dataclasses import replace
from typing import Any

from app.ml.feature_schema import FeatureRecord
from app.risk.policy import assess_risk
from app.risk.policy_config import DEFAULT_POLICY, PolicyConfig, RiskLayer
from app.risk.types import MlOutputs, RiskAssessment, RiskInputs

SCALE_FACTORS = (0.8, 1.2)
SENSITIVITY_FORMAT = "provenancex-fusion-sensitivity-v1"
BLEND_PARAMETER = "max_blend"


def inputs_from_validation(
    records: Sequence[FeatureRecord], outputs: Sequence[MlOutputs | None]
) -> list[RiskInputs]:
    """Build risk inputs. Any record outside the validation split is refused."""
    wrong = sorted({record.split for record in records} - {"validation"})
    if wrong:
        raise ValueError(f"Sensitivity analysis may only use the validation split, got {wrong}")
    if len(records) != len(outputs):
        raise ValueError("Each record needs exactly one ML output")
    return [
        RiskInputs(
            artifact_type=record.artifact_type,
            features=record.features,
            null_reasons=record.null_reasons,
            ml=output,
            record_id=record.record_id,
        )
        for record, output in zip(records, outputs, strict=True)
    ]


def _assess(inputs: Sequence[RiskInputs], policy: PolicyConfig) -> list[RiskAssessment]:
    return [assess_risk(item, policy) for item in inputs]


def _compare(
    base: list[RiskAssessment], changed: list[RiskAssessment], parameter: str, factor: float
) -> dict[str, Any]:
    transitions: Counter[str] = Counter()
    shifts = []
    for before, after in zip(base, changed, strict=True):
        if before.decision != after.decision:
            transitions[f"{before.decision}->{after.decision}"] += 1
        if before.risk_score is not None and after.risk_score is not None:
            shifts.append(abs(before.risk_score - after.risk_score))
    return {
        "parameter": parameter,
        "factor": factor,
        "decisions_changed": sum(transitions.values()),
        "share_changed": sum(transitions.values()) / len(base),
        "transitions": dict(sorted(transitions.items())),
        "mean_absolute_score_change": sum(shifts) / len(shifts) if shifts else 0.0,
    }


def run_sensitivity(
    inputs: Sequence[RiskInputs], policy: PolicyConfig = DEFAULT_POLICY
) -> dict[str, Any]:
    """Change each weight, and the blend, by each factor, one at a time."""
    if not inputs:
        raise ValueError("Sensitivity analysis needs at least one record")
    base = _assess(inputs, policy)
    rows = []
    for factor in SCALE_FACTORS:
        for layer in RiskLayer:
            changed = _assess(inputs, policy.with_scaled_weight(layer, factor))
            rows.append(_compare(base, changed, str(layer), factor))
        blended = replace(policy, max_blend=min(1.0, policy.max_blend * factor))
        rows.append(_compare(base, _assess(inputs, blended), BLEND_PARAMETER, factor))
    return {
        "format": SENSITIVITY_FORMAT,
        "records": len(base),
        "baseline_decisions": dict(sorted(Counter(a.decision for a in base).items())),
        "rows": rows,
    }


def render_markdown(result: dict[str, Any], dataset_sha256: str, policy_version: str) -> str:
    lines = [
        "# ProvenanceX fusion sensitivity",
        "",
        "> **WARNING: SYNTHETIC DATA, ANALYSIS ONLY.** This report covers the validation split of "
        "the synthetic dataset. The weights and thresholds are hand-set research parameters that "
        "have not been tuned or validated. It fits nothing, does not use the test split, and "
        "does not show that any decision is correct.",
        "",
        "Generated by `ml/scripts/fusion_sensitivity.py`. Do not edit by hand.",
        "",
        f"- Records: {result['records']} (validation split)",
        f"- Dataset SHA-256: `{dataset_sha256}`",
        f"- Policy: `{policy_version}`",
        f"- Baseline decisions: {result['baseline_decisions']}",
        "",
        "Validation records hold features only, so hard rules and layers that need findings or "
        "provenance checks (such as `download_integrity`) are not exercised here.",
        "",
        "ML weights change no decision by construction, because ML cannot change the decision. "
        "Their rows are kept to show that, and the score still moves.",
        "",
        "| Parameter | Factor | Decisions changed | Share | Transitions | Mean score change |",
        "|---|---|---|---|---|---|",
    ]
    for row in result["rows"]:
        moves = ", ".join(f"{k}: {v}" for k, v in row["transitions"].items()) or "none"
        lines.append(
            f"| {row['parameter']} | {row['factor']:.1f} | {row['decisions_changed']} | "
            f"{row['share_changed']:.3f} | {moves} | {row['mean_absolute_score_change']:.4f} |"
        )
    return "\n".join(lines) + "\n"
